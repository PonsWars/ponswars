#!/usr/bin/env node
/**
 * Generates the Merkle conformance fixture.
 *
 * `contracts/test/MerkleConformance.t.sol` reads this file and drives the real
 * `RewardsDistributor` with proofs produced by `@ponswars/rewards-math`. That
 * is the only thing standing between the TypeScript tree builder and the
 * Solidity verifier drifting apart — and if they drift, either a whole
 * distribution becomes unclaimable or a crafted proof pays out SPY nobody
 * allocated.
 *
 * `--check` fails when the committed fixture no longer matches what the current
 * builder produces, so a change to the leaf encoding or the pairing rule cannot
 * land without the conformance test being regenerated and re-run.
 *
 * Seven entries deliberately: an odd count exercises the promoted-node path at
 * more than one level, which an even count would never reach.
 */
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'contracts', 'test', 'fixtures', 'merkle.json');

const { buildMerkleTree } = await import(
  pathToFileURL(join(root, 'packages/rewards-math/dist/merkle.js')).href
);

const DISTRIBUTION_ID = 42n;

// Six decimals, matching the contract tests. SPY decimals are OPEN and nothing
// here may assume 18.
const ONE_SPY = 1_000_000n;

const wallet = (n) => `0x${n.toString(16).padStart(40, '0')}`;

const entries = [
  { wallet: wallet(0x11), amount: 1n * ONE_SPY },
  { wallet: wallet(0x22), amount: 2n * ONE_SPY },
  { wallet: wallet(0x33), amount: 3n * ONE_SPY },
  { wallet: wallet(0x44), amount: 4n * ONE_SPY },
  { wallet: wallet(0x55), amount: 5n * ONE_SPY },
  { wallet: wallet(0x66), amount: 6n * ONE_SPY },
  { wallet: wallet(0x77), amount: 7n * ONE_SPY },
];

const tree = buildMerkleTree(DISTRIBUTION_ID, entries);

const fixture = {
  _comment:
    'Generated by scripts/generate-merkle-fixture.mjs. Do not edit by hand. Regenerate with: node scripts/generate-merkle-fixture.mjs',
  distributionId: DISTRIBUTION_ID.toString(),
  root: tree.root,
  total: tree.total.toString(),
  // Written out explicitly: forge's JSON cheatcodes have no array-length
  // wildcard, so the Solidity side needs the count as a field.
  claimCount: tree.claims.length,
  claims: tree.claims.map((claim) => ({
    wallet: claim.wallet,
    amount: claim.amount.toString(),
    leaf: claim.leaf,
    proof: [...claim.proof],
  })),
};

const rendered = `${JSON.stringify(fixture, null, 2)}\n`;

if (process.argv.includes('--check')) {
  let existing = '';
  try {
    existing = readFileSync(target, 'utf8');
  } catch {
    console.error('Merkle fixture is missing. Run: node scripts/generate-merkle-fixture.mjs');
    process.exit(1);
  }
  if (existing !== rendered) {
    console.error(
      'Merkle fixture is stale — the tree builder produces a different tree than the committed fixture.\n' +
        'Regenerate it and re-run the contract tests: node scripts/generate-merkle-fixture.mjs',
    );
    process.exit(1);
  }
  console.log(`Merkle fixture matches the builder (${String(fixture.claims.length)} claims)`);
} else {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, rendered);
  console.log(`wrote ${target} (root ${fixture.root})`);
}
