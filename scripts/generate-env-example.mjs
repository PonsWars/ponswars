#!/usr/bin/env node
/**
 * Regenerates `.env.example` from the parameter table in `@ponswars/config`.
 *
 * The file an operator reads and the table the loader enforces come from one
 * source, so they cannot drift. `verify.sh` runs this with `--check`, which
 * fails when a parameter has been added without regenerating the example — or
 * without adding it to the hand-written mainnet template, checked below.
 *
 * Values are placeholders and are deliberately non-functional. `.env.example`
 * is the one place a placeholder may exist — `packages/config` itself has no
 * defaults, because a default for an OPEN parameter is a silent product
 * decision (masterplan §102).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, '.env.example');

// On Windows an absolute path is not a valid ESM specifier — it must be a
// file:// URL, or the loader reads the drive letter as a protocol.
const { describeParameters } = await import(
  pathToFileURL(join(root, 'packages/config/dist/index.js')).href
);

/** Placeholder shown for each parameter. Never a usable production value. */
const PLACEHOLDERS = {
  NODE_ENV: 'development',
  CHAIN_ID: '<chain id>',
  RPC_URL: '<rpc endpoint url>',
  WAR_TOKEN_ADDRESS: '0x0000000000000000000000000000000000000000',
  SPY_TOKEN_ADDRESS: '0x0000000000000000000000000000000000000000',
  SPY_TOKEN_DECIMALS: '<read from chain>',
  WAR_TOKEN_DECIMALS: '<read from chain>',
  REWARDS_DISTRIBUTOR_ADDRESS: '0x0000000000000000000000000000000000000000',
  SECRET_STOCK_VAULT_ADDRESS: '0x0000000000000000000000000000000000000000',
  SECRET_RESERVER_KEY: 'disabled',
  DATABASE_URL: 'postgres://user:password@localhost:5432/ponswars',
  REDIS_URL: 'redis://localhost:6379',
  MIN_CLAIM_THRESHOLD_SPY: '0.001',
  PRICE_FEED_STALE_AFTER_MS: '<calibrate per source>',
  ENGINE_CALIBRATION_FILE: 'tools/calibration/initial-candidate.json',
  VOLUME_FEED_STALE_AFTER_MS: '<calibrate per source>',
  PONS_FEED_STALE_AFTER_MS: '<calibrate per source>',
  BATTLE_ENGINE_TICK_MS: '1000',
  // Non-functional on purpose, unlike the reserver's `disabled`: whether anyone
  // is told when a round stops finalizing is a choice each deployment makes.
  ALERT_WEBHOOK: '<disabled | ntfy+https://… | json+https://…>',
  ALERT_ROUND_STUCK_AFTER_MS: '<decide per deployment>',
};

const GROUP_TITLES = {
  runtime: 'Runtime',
  chain: 'Chain and contracts',
  storage: 'Storage',
  rewards: 'Rewards',
  feeds: 'Market and chain feeds',
};

const wrap = (text, width = 76) => {
  const words = text.split(/\s+/);
  const lines = [];
  let line = '';
  for (const word of words) {
    if (line.length + word.length + 1 > width) {
      lines.push(line);
      line = word;
    } else {
      line = line.length === 0 ? word : `${line} ${word}`;
    }
  }
  if (line.length > 0) lines.push(line);
  return lines;
};

const parameters = describeParameters();
const groups = [...new Set(parameters.map((p) => p.group))];

const out = [
  '# PonsWars environment contract',
  '#',
  '# Generated by scripts/generate-env-example.mjs from the parameter table in',
  '# packages/config. Do not edit by hand — run `node scripts/generate-env-example.mjs`.',
  '#',
  '# Every variable below is REQUIRED. Nothing here has a default: masterplan §102',
  '# forbids inventing an OPEN value and shipping it as product policy, so startup',
  '# fails with the full list of what is missing rather than guessing (§65.2).',
  '#',
  '# The values shown are placeholders and will not work. See docs/OPEN_PARAMETERS.md',
  '# for what each one still needs decided.',
  '',
];

for (const group of groups) {
  out.push(`# ${'-'.repeat(74)}`);
  out.push(`# ${GROUP_TITLES[group] ?? group}`);
  out.push(`# ${'-'.repeat(74)}`);
  out.push('');
  for (const parameter of parameters.filter((p) => p.group === group)) {
    for (const line of wrap(parameter.description)) {
      out.push(`# ${line}`);
    }
    if (parameter.secret) {
      out.push('# SECRET — never commit a real value and never log it.');
    }
    out.push(`${parameter.name}=${PLACEHOLDERS[parameter.name] ?? '<required>'}`);
    out.push('');
  }
}

const rendered = `${out.join('\n').trimEnd()}\n`;

/**
 * The mainnet template is written by hand, because its values are decisions
 * with reasons beside them rather than placeholders. What can drift is checked
 * here instead of trusted:
 *
 * - it names every parameter the server requires and every variable the
 *   composition interpolates, once, and nothing else;
 * - every market bound it labels as measured is the value the replay ran with,
 *   so the label cannot outlive a change to either file;
 * - the calibration file it points the server at exists in the directory the
 *   compose file mounts.
 */
const MAINNET_TEMPLATE = 'infra/deployment/mainnet.env.template';

/** Variables the compose file reads that are not the server's (deployment.md). */
const COMPOSITION = [
  'POSTGRES_USER',
  'POSTGRES_PASSWORD',
  'POSTGRES_DB',
  'VITE_API_URL',
  'VITE_WS_URL',
  'WEB_PORT',
  'SITE_DOMAIN',
];

function checkMainnetTemplate(parameterNames) {
  const problems = [];
  let text;
  try {
    text = readFileSync(join(root, MAINNET_TEMPLATE), 'utf8');
  } catch {
    return [`${MAINNET_TEMPLATE} is missing`];
  }
  const values = new Map();
  for (const line of text.split(/\r?\n/)) {
    const match = /^([A-Z][A-Z0-9_]*)=(.*)$/.exec(line);
    if (match === null) continue;
    if (values.has(match[1])) problems.push(`${match[1]} is set twice`);
    values.set(match[1], match[2]);
  }

  const expected = new Set([...parameterNames, ...COMPOSITION]);
  for (const name of expected) {
    if (!values.has(name)) problems.push(`${name} is missing`);
  }
  for (const name of values.keys()) {
    if (!expected.has(name)) problems.push(`${name} is not a parameter or a composition variable`);
  }

  const file = values.get('ENGINE_CALIBRATION_FILE') ?? '';
  const mounted = '/app/calibration/';
  if (!file.startsWith(mounted)) {
    problems.push(`ENGINE_CALIBRATION_FILE must be under ${mounted}, where compose mounts it`);
  } else {
    const local = join(root, 'tools', 'calibration', file.slice(mounted.length));
    let candidate;
    try {
      candidate = JSON.parse(readFileSync(local, 'utf8'));
    } catch {
      problems.push(
        `ENGINE_CALIBRATION_FILE names ${file}, but tools/calibration has no such JSON`,
      );
    }
    for (const [name, value] of Object.entries(candidate?.market ?? {})) {
      if (values.has(name) && values.get(name) !== value) {
        problems.push(`${name} is ${values.get(name)}, but the replayed candidate ran ${value}`);
      }
    }
  }
  return problems;
}

if (process.argv.includes('--check')) {
  let existing = '';
  try {
    existing = readFileSync(target, 'utf8');
  } catch {
    console.error('.env.example is missing. Run: node scripts/generate-env-example.mjs');
    process.exit(1);
  }
  if (existing !== rendered) {
    console.error('.env.example is stale. Run: node scripts/generate-env-example.mjs');
    process.exit(1);
  }
  console.log('.env.example is in sync with packages/config');

  const problems = checkMainnetTemplate(parameters.map((p) => p.name));
  if (problems.length > 0) {
    console.error(`${MAINNET_TEMPLATE} disagrees with what it deploys:`);
    for (const problem of problems) {
      console.error(`  ${problem}`);
    }
    process.exit(1);
  }
  console.log(`${MAINNET_TEMPLATE} names every parameter, and runs what was replayed`);
} else {
  writeFileSync(target, rendered);
  console.log(`wrote ${target} (${String(parameters.length)} parameters)`);
}
